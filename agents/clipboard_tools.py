"""Watches the clipboard and tidies two kinds of copied text.

- A uniformly indented block (code copied from the middle of a file): remove the common
  indentation and trailing whitespace. Other formats on the clipboard are kept, so
  rich-text pastes are unaffected.
- A bare URL: strip tracking parameters and turn it into a Markdown link using the page
  title. Titles are not fetched for private hosts or links that look single-use.
"""
import ipaddress
import re
import textwrap
import threading
import time
import urllib.parse
import urllib.request
from html.parser import HTMLParser

from lib.common import run_main

POLL_SECONDS = 0.5
FETCH_TIMEOUT = 3
FETCH_DEADLINE = 6

PLAIN = "public.utf8-plain-text"
# Other plain-text flavours that would go stale once we rewrite the string.
STALE_TEXT_TYPES = {"public.utf16-plain-text", "public.utf16-external-plain-text",
                    "com.apple.traditional-mac-plain-text"}
# Password managers and files: never touch.
SKIP_TYPES = {"org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType",
              "org.nspasteboard.AutoGeneratedType", "com.agilebits.onepassword", "public.file-url"}

URL_RE = re.compile(r"^https?://\S+$")
TRACKING_PARAMS = {"fbclid", "gclid", "dclid", "gbraid", "wbraid", "msclkid", "yclid", "twclid",
                   "igshid", "mc_cid", "mc_eid", "ref_src", "ref_url", "_hsenc", "_hsmi"}
SHARE_ID_HOSTS = ("youtube.com", "youtu.be", "spotify.com")  # "si" is a share tracker only here
# Titles are only fetched from these sites (and their subdomains); other links are left bare
# so copying a URL never announces it to a site you haven't chosen to trust.
TITLE_FETCH_HOSTS = ("github.com", "wikipedia.org", "stackoverflow.com", "stackexchange.com",
                     "youtube.com", "youtu.be", "python.org", "developer.apple.com",
                     "developer.mozilla.org", "cran.r-project.org")
SINGLE_USE_RE = re.compile(
    r"token|secret|passw|signature|sig=|auth|session|otp|magic|unsubscribe|confirm|verify"
    r"|reset|invite|api_?key|access_?key|x-amz-|code=|key=", re.IGNORECASE)


def normalize_code(text):
    """Return the dedented text, or None if there is no common indentation to remove."""
    if "\r" in text or sum(1 for line in text.split("\n") if line.strip()) < 2:
        return None
    dedented = textwrap.dedent(text)
    if dedented == text:
        return None
    return "\n".join(line.rstrip() for line in dedented.split("\n"))


def _is_tracking(key, host):
    key = key.lower()
    if key.startswith("utm_") or key in TRACKING_PARAMS:
        return True
    return key == "si" and any(host == h or host.endswith("." + h) for h in SHARE_ID_HOSTS)


def clean_url(url):
    """Drop tracking parameters, leaving the rest of the query string byte-for-byte intact."""
    parts = urllib.parse.urlsplit(url)
    if not parts.query:
        return url
    host = (parts.hostname or "").lower()
    kept = [pair for pair in parts.query.split("&") if not _is_tracking(pair.split("=", 1)[0], host)]
    return urllib.parse.urlunsplit(parts._replace(query="&".join(kept)))


def is_safe_to_fetch(url):
    parts = urllib.parse.urlsplit(url)
    host = (parts.hostname or "").lower()
    if parts.username or "." not in host or host.endswith((".local", ".internal", ".lan")):
        return False
    if not any(host == h or host.endswith("." + h) for h in TITLE_FETCH_HOSTS):
        return False
    try:
        ipaddress.ip_address(host)
        return False
    except ValueError:
        pass
    return not SINGLE_USE_RE.search(parts.path + "?" + parts.query)


class TitleParser(HTMLParser):
    def __init__(self):
        super().__init__()
        self.in_title = False
        self.done = False
        self.pieces = []

    def handle_starttag(self, tag, attrs):
        if tag == "title" and not self.done:
            self.in_title = True

    def handle_endtag(self, tag):
        if tag == "title" and self.in_title:
            self.in_title = False
            self.done = True

    def handle_data(self, data):
        if self.in_title:
            self.pieces.append(data)


def _fetch_title(url, result):
    try:
        request = urllib.request.Request(
            url, headers={"User-Agent": "Mozilla/5.0 (Macintosh; Intel Mac OS X 10_15_7)"})
        with urllib.request.urlopen(request, timeout=FETCH_TIMEOUT) as response:
            if "text/html" not in response.headers.get("Content-Type", ""):
                return
            charset = response.headers.get_content_charset() or "utf-8"
            chunk = response.read(65536).decode(charset, errors="ignore")
        parser = TitleParser()
        parser.feed(chunk)
        title = " ".join("".join(parser.pieces).split())[:200]
        result.append(title.replace("[", "\\[").replace("]", "\\]"))
    except Exception:
        pass


def fetch_title(url):
    result = []
    thread = threading.Thread(target=_fetch_title, args=(url, result), daemon=True)
    thread.start()
    thread.join(FETCH_DEADLINE)
    return result[0] if result else ""


def format_url(url):
    cleaned = clean_url(url)
    title = fetch_title(cleaned) if is_safe_to_fetch(cleaned) else ""
    return f"[{title}]({cleaned})" if title else cleaned


def replace_string(pasteboard, text, keep_other_formats):
    """Swap the clipboard's plain text, optionally preserving its other representations."""
    from AppKit import NSPasteboardItem

    new_item = NSPasteboardItem.alloc().init()
    if keep_other_formats:
        items = pasteboard.pasteboardItems()
        if not items or len(items) != 1:
            return False
        for kind in items[0].types():
            if kind == PLAIN or kind in STALE_TEXT_TYPES:
                continue
            data = items[0].dataForType_(kind)
            if data is not None:
                new_item.setData_forType_(data, kind)
    new_item.setString_forType_(text, PLAIN)
    pasteboard.clearContents()
    return bool(pasteboard.writeObjects_([new_item]))


def process(pasteboard, log):
    """Inspect the clipboard once and rewrite it if needed. Returns True if it was rewritten."""
    seen = pasteboard.changeCount()
    if SKIP_TYPES & set(pasteboard.types() or []):
        return False
    text = pasteboard.stringForType_(PLAIN)
    if not text:
        return False

    stripped = text.strip()
    if URL_RE.match(stripped):
        formatted = format_url(stripped)
        # The title fetch takes a moment; leave the clipboard alone if it moved on meanwhile.
        if formatted == stripped or pasteboard.changeCount() != seen:
            return False
        log.info("url rewritten (%s)", urllib.parse.urlsplit(stripped).hostname)
        return replace_string(pasteboard, formatted, keep_other_formats=False)

    normalized = normalize_code(text)
    if normalized is None:
        return False
    log.info("dedented %d lines", normalized.count("\n") + 1)
    return replace_string(pasteboard, normalized, keep_other_formats=True)


def main(log):
    from AppKit import NSPasteboard

    pasteboard = NSPasteboard.generalPasteboard()
    last = pasteboard.changeCount()
    log.info("started")
    while True:
        if pasteboard.changeCount() != last:
            try:
                process(pasteboard, log)
            except Exception:
                log.exception("failed to process clipboard")
            last = pasteboard.changeCount()
        time.sleep(POLL_SECONDS)


if __name__ == "__main__":
    run_main("clipboard_tools", main)
